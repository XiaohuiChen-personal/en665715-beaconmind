class CarMeasurements:
    """A car measurement CSV read with write_car_json.read_csv: {quantity: Reading} after the superseding rule (a
    <q>_corrected / _recheck / _remeasure / _remeasure<N> row replaces <q>; a row whose notes start with SUPERSEDED is
    not an input; text rows are skipped), values in SI units (m, kg), each the mean of its readings.

    m[key] looks a quantity up the way the writer looks up car.json's keys: the plan key first (wheel_width_m), then
    the 2026-10-10 row name in write_car_json.ROW_FOR_KEY (W2_tyre_width). Other rows are looked up by their own name.
    """

    def __init__(self, path, writer):
        self.path, self.writer = Path(path), writer
        self.rows = writer.read_csv(self.path.read_text(encoding="utf-8"))

    def reading(self, key):
        found = self.rows.get(key)
        alias = self.writer.ROW_FOR_KEY.get(key)
        if found is None and alias is not None:
            found = self.rows.get(alias)
        if found is None:
            raise KeyError(f"{self.path} has no usable row {key}" + (f" or {alias}" if alias else ""))
        return found

    def __getitem__(self, key):
        return self.reading(key).value

    def wheel_diameter(self):
        """As write_car_json.py: the mean of the two wheels' roll-out diameters (distance / (ROLLOUT_REVS pi)) when
        both roll-outs were measured, else the direct reading W1_tyre_diameter_direct."""
        if "rollout_left_m" in self.rows and "rollout_right_m" in self.rows:
            revs = self.writer.ROLLOUT_REVS
            return sum(self[f"rollout_{side}_m"] / (revs * math.pi) for side in ("left", "right")) / 2
        return self["W1_tyre_diameter_direct"]

    def imu_z_above_axle(self):
        """As write_car_json.py: an imu_z_m row (already above the axle) as it is, else the board-top height above the
        FLOOR (S1_imu_board_top_h) minus the wheel radius."""
        if "imu_z_m" in self.rows:
            return self["imu_z_m"]
        return self[self.writer.IMU_TOP_ROW] - self.wheel_diameter() / 2


