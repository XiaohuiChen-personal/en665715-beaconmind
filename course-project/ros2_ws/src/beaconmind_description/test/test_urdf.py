def test_power_bank_box_matches_measurements(robot, meas, extras_meas):
    """The chassis box power_bank (collision and visual) is the M1.T16 power bank (2026-10-29, rows B15_bank_* of the
    extras source CSV): x from -B15_bank_rear_x to -B15_bank_front_x (both read as distances BEHIND the axle line),
    y +-B15_bank_width / 2 (centred), floor heights B15_bank_bottom_h to B15_bank_bottom_h + B15_bank_height (model
    z = floor height - the wheel radius from `meas`). It is the lowest chassis box, and its top is not above the
    MEASURED plate underside at the rear, where it sits (B8_plate_underside_h_rear; the level model plate is higher)."""
    r = meas.wheel_diameter() / 2
    front, rear = extras_meas["B15_bank_front_x"], extras_meas["B15_bank_rear_x"]
    width, bottom, height = (extras_meas[k] for k in ("B15_bank_width", "B15_bank_bottom_h", "B15_bank_height"))
    expected = [(-rear, -front), (-width / 2, width / 2), (bottom - r, bottom + height - r)]
    # The readings agree with each other: "centred, 18 mm to each tyre" against (track inner - bank width) / 2, within
    # the 2 mm ruler rule.
    gap = (meas["track_inner_m"] - width) / 2
    assert abs(gap - extras_meas["B15_bank_tyre_gap"]) <= 0.002, f"bank-to-tyre gap {gap} m vs the reading"
    for element in ("collision", "visual"):
        boxes = dict(boxes_in_base(robot, "chassis_link", element))
        name = f"power_bank_{element}"
        assert name in boxes, f"chassis_link has no {element} box named {name}"
        box = boxes[name]
        for axis, (lo, hi), (e_lo, e_hi) in zip("xyz", box, expected):
            assert abs(lo - e_lo) <= MEAS_TOL and abs(hi - e_hi) <= MEAS_TOL, \
                f"{name} {axis} spans ({lo}, {hi}) m, the readings give ({e_lo}, {e_hi}) m"
        others = {n: b for n, b in boxes.items() if n != name}
        lowest = min(others, key=lambda n: others[n][2][0])
        assert box[2][0] < others[lowest][2][0], f"{name} is not the lowest chassis box ({lowest} is as low)"
        plate_rear = extras_meas["B8_plate_underside_h_rear"] - r
        assert box[2][1] <= plate_rear + TOL, \
            f"{name} top {box[2][1]} m is above the measured rear plate underside {plate_rear} m (B8 rear)"


def test_inertias_are_physical_and_chassis_is_the_uniform_box(robot, meas, car_json_path):
    """(a) Every link's <inertia> is a valid solid-body inertia about principal axes: zero products of inertia,
    positive moments, and ixx + iyy >= izz, ixx + izz >= iyy, iyy + izz >= ixx.
    (b) chassis_link's inertia is the uniform solid box of its own mass with sx = the plate length
    B1_plate_front_x + B2_plate_rear_x (`meas`, after the superseding rule), sy = B5_plate_width_narrow and
    sz = car.json chassis_height_m: ixx = m (sy^2 + sz^2) / 12 and so on, within a relative 1e-9. A swapped edge in the
    chassis inertia call passes (a) and fails (b)."""
    checked = 0
    for lk in robot.findall("link"):
        inertial = lk.find("inertial")
        if inertial is None:
            continue
        checked += 1
        el, name = inertial.find("inertia"), lk.get("name")
        v = {k: float(el.get(k)) for k in ("ixx", "ixy", "ixz", "iyy", "iyz", "izz")}
        assert v["ixy"] == v["ixz"] == v["iyz"] == 0.0, f"{name}: non-zero products of inertia {v}"
        assert min(v["ixx"], v["iyy"], v["izz"]) > 0.0, f"{name}: a principal moment is not positive {v}"
        for a, b, c in (("ixx", "iyy", "izz"), ("ixx", "izz", "iyy"), ("iyy", "izz", "ixx")):
            assert v[a] + v[b] >= v[c] * (1 - 1e-12), f"{name}: {a} + {b} < {c} ({v})"
    # base_link and camera_optical_frame carry no <inertial> (KDL root link; a pure frame).
    assert checked == len(EXPECTED_LINKS) - 2, f"{checked} links have an <inertial>"
    sx = meas["B1_plate_front_x"] + meas["B2_plate_rear_x"]
    sy = meas["B5_plate_width_narrow"]
    sz = json.loads(car_json_path.read_text(encoding="utf-8"))["values"]["chassis_height_m"]["value"]
    chassis = link(robot, "chassis_link").find("inertial")
    m = float(chassis.find("mass").get("value"))
    expected = {"ixx": m * (sy ** 2 + sz ** 2) / 12, "iyy": m * (sx ** 2 + sz ** 2) / 12,
                "izz": m * (sx ** 2 + sy ** 2) / 12}
    for k, want in expected.items():
        got = float(chassis.find("inertia").get(k))
        assert abs(got - want) <= 1e-9 * want, (
            f"chassis_link {k} = {got}, the uniform box of {m} kg and {sx} x {sy} x {sz} m gives {want}")


def test_plate_outline_matches_measurements(robot, meas, writer, car_json_path):
    """The plate boxes follow the plate rows of the CSV car.json names (added 2026-10-16 with the plate CAD; before, the
    hand-written plate values in car_geometry_extras.xacro were not checked against any CSV): rear apex at -B2, wing
    shoulder at -B2 + B5b, the 100 mm strip, the half-ellipse wing slices, and the front: square at B1, or, when the
    CSV has the CAD outline rows P1/P2, the full-width strip ending where the corner fillets start and the front slices
    as wide as the rounded outline at their middles, up to the apex at B1."""
    plate = {name.replace("_collision", ""): box for name, box in boxes_in_base(robot, "chassis_link")
             if name and name.startswith("plate_")}
    b1, b2 = meas["B1_plate_front_x"], meas["B2_plate_rear_x"]
    b5n, b5b, b5m = meas["B5_plate_width_narrow"], meas["B5b_wing_depth_centre"], meas["chassis_width_m"]
    assert abs(min(b[0][0] for b in plate.values()) + b2) <= MEAS_TOL, "rear apex is not at -B2"
    assert abs(max(b[0][1] for b in plate.values()) - b1) <= MEAS_TOL, "front apex is not at B1"
    strip = plate["plate_strip"]
    assert abs(strip[0][0] - (-b2 + b5b)) <= MEAS_TOL, "the strip does not start at the wing shoulder -B2 + B5b"
    assert abs(strip[1][1] - b5n / 2) <= MEAS_TOL and abs(strip[1][0] + b5n / 2) <= MEAS_TOL, "strip width is not B5"
    wings = sorted((b for n, b in plate.items() if n.startswith("plate_wing_")), key=lambda b: b[0][0])
    assert len(wings) == 4
    for i, box in enumerate(wings, start=1):
        d = (i - 0.5) * b5b / 4
        width = b5m * math.sqrt(1 - ((b5b - d) / b5b) ** 2)
        assert abs((box[1][1] - box[1][0]) - width) <= MEAS_TOL, f"wing slice {i} width"
    fronts = sorted((b for n, b in plate.items() if n.startswith("plate_front_")), key=lambda b: b[0][0])
    if "P1_plate_front_arc_radius" not in meas.rows or "P2_plate_front_corner_radius" not in meas.rows:
        pytest.fail("the CSV car.json names has no plate-front outline rows P1/P2, but the URDF draws a rounded front")
    big, small = meas["P1_plate_front_arc_radius"], meas["P2_plate_front_corner_radius"]
    g = writer.car_model.rounded_front(b1, b5n / 2, big, small)
    (xf, yf), cx, xt = g["fillet_centre"], g["arc_centre_x"], g["arc_tangent"][0]
    assert abs(strip[0][1] - xf) <= MEAS_TOL, "the full-width strip does not end where the corner fillets start"
    assert len(fronts) == 3 and abs(fronts[0][0][0] - xf) <= MEAS_TOL
    for i, box in enumerate(fronts, start=1):
        xm = (box[0][0] + box[0][1]) / 2
        half = yf + math.sqrt(small ** 2 - (xm - xf) ** 2) if xm <= xt else math.sqrt(big ** 2 - (xm - cx) ** 2)
        assert abs((box[1][1] - box[1][0]) - 2 * half) <= MEAS_TOL, f"front slice {i} width"
    # car.json's plate-front corners are the rounded outline's farthest points (the same CSV rows, the same formula).
    fx, fy = writer.car_model.rounded_front_corner(b1, b5n / 2, big, small)
    corners = json.loads(car_json_path.read_text(encoding="utf-8"))["values"]["corners"]["value"]
    for s in (1, -1):
        assert any(abs(x - fx) <= MEAS_TOL and abs(y - s * fy) <= MEAS_TOL for x, y in corners), (fx, s * fy, corners)


def test_every_visual_has_inline_colour(robot):
    """Every <visual> carries its own <material name=...><color rgba=.../></material>, and one name means one rgba.

    Gazebo Fortress's URDF-to-SDF step (sdformat 12) resolves a by-name <material> only for the FIRST <visual> of
    a link, so a name-only reference on any later visual came out black (diffuse 0 0 0 1).
    """
    visuals = robot.findall("link/visual")
    assert visuals, "the URDF has no <visual> at all"
    rgba_of = {}
    for vis in visuals:
        label = vis.get("name")
        mats = vis.findall("material")
        assert len(mats) == 1, f"{label}: expected one <material>, found {len(mats)}"
        name = mats[0].get("name")
        colours = mats[0].findall("color")
        assert len(colours) == 1, f"{label}: material {name} has no inline <color> (a by-name reference)"
        rgba = floats(colours[0].get("rgba"))
        assert len(rgba) == 4 and all(0.0 <= c <= 1.0 for c in rgba), f"{label}: rgba {rgba}"
        assert any(c > 0.0 for c in rgba[:3]), f"{label}: {name} is pure black, the colour of a lost material"
        assert rgba_of.setdefault(name, rgba) == rgba, f"colour {name} has two rgba values: {rgba_of[name]} and {rgba}"
