def test_wheel_separation_equals_track_width(robot, meas):
    # track_outer_m / track_inner_m (W3 on 2026-10-10): wheel centre to wheel centre = (outer + inner) / 2
    track_width = (meas["track_outer_m"] + meas["track_inner_m"]) / 2
    y = {}
    for side in ("left", "right"):
        j = joint(robot, f"{side}_wheel_joint")
        assert j.get("type") == "continuous"
        assert j.find("parent").get("link") == "base_link"
        assert j.find("child").get("link") == f"{side}_wheel_link"
        xyz, rpy = joint_origin(j)
        assert abs(xyz[0]) <= TOL and abs(xyz[2]) <= TOL, "wheel centres must lie on the axle line at z = 0"
        # Whatever the joint convention, the spin axis in base_link must be +y.
        axis = floats(j.find("axis").get("xyz") if j.find("axis") is not None else "1 0 0")
        assert close(matvec(rpy_matrix(*rpy), axis), [0.0, 1.0, 0.0]), f"{side} wheel does not spin about +y"
        y[side] = xyz[1]
    assert abs(y["left"] + y["right"]) <= TOL, "the wheels must sit symmetrically about base_link"
    assert abs(y["left"] - track_width / 2) <= MEAS_TOL
    assert abs(y["right"] + track_width / 2) <= MEAS_TOL
    assert abs((y["left"] - y["right"]) - track_width) <= MEAS_TOL


def test_wheel_radius_half_diameter(robot, meas):
    # roll-out mean, else the direct W1 reading (CarMeasurements.wheel_diameter); wheel_width_m (W2 on 2026-10-10)
    radius = meas.wheel_diameter() / 2
    width = meas["wheel_width_m"]
    for side in ("left", "right"):
        lk = link(robot, f"{side}_wheel_link")
        cylinders = lk.findall("visual/geometry/cylinder")
        spheres = lk.findall("collision/geometry/sphere")
        assert len(cylinders) == 1 and len(spheres) == 1
        assert abs(float(cylinders[0].get("radius")) - radius) <= MEAS_TOL
        assert abs(float(cylinders[0].get("length")) - width) <= MEAS_TOL
        assert float(spheres[0].get("radius")) == float(cylinders[0].get("radius"))


