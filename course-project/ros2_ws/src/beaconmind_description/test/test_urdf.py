def test_props_files_do_not_overlap():
    """car_props.xacro (generated) and car_geometry_extras.xacro (hand-written) define disjoint property sets.

    xacro lets a later definition replace an earlier one without a warning, so a property in both files would
    silently override the generated car.json value with the hand-written one.
    """
