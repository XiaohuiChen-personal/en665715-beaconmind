def optical_pose(robot):
    """(R, t) of camera_optical_frame in base_link, composed from camera_joint and camera_optical_joint."""
    cam, opt = joint(robot, "camera_joint"), joint(robot, "camera_optical_joint")
    assert cam.find("parent").get("link") == "base_link" and cam.find("child").get("link") == "camera_link"
    assert opt.find("parent").get("link") == "camera_link" and opt.find("child").get("link") == "camera_optical_frame"
    t1, rpy1 = joint_origin(cam)
    t2, rpy2 = joint_origin(opt)
    r1 = rpy_matrix(*rpy1)
    return matmul(r1, rpy_matrix(*rpy2)), [a + b for a, b in zip(matvec(r1, t2), t1)]


def test_optical_frame_matches_camera_json(robot, car_json_path):
    """M2.T4: base_link -> camera_optical_frame equals camera.json extrinsics within 1e-6 m and 1e-6 rad.

    Skips only while configs/camera.json does not exist. Translation: x_m, y_m and z_m - wheel_radius (z_m is above
    the floor, base_link at axle height). Rotation: the rpy_matrix of roll/pitch/yaw against the composed rotation.
    """
    camera_path = car_json_path.parent / "camera.json"
    if not camera_path.is_file():
        pytest.skip(f"{camera_path} (M1.T7 calibration) does not exist yet; test_optical_frame_pose_from_measurements "
                    "checks the measured lens position (mount angles ASSUMED 0) meanwhile")
    ext = json.loads(camera_path.read_text(encoding="utf-8")).get("extrinsics") or {}
    needed = ("x_m", "y_m", "z_m", "roll_deg", "pitch_deg", "yaw_deg")
    absent = [k for k in needed if not isinstance(ext.get(k), (int, float))]
    assert not absent, f"{camera_path} extrinsics lack numbers for {absent}"
    assert ext.get("parent", "base_link") == "base_link" and ext.get("child", "camera_optical_frame") == \
        "camera_optical_frame", f"extrinsics are {ext.get('parent')} -> {ext.get('child')}"
    rot, trans = optical_pose(robot)
    wheel_radius = float(link(robot, "left_wheel_link").find("visual/geometry/cylinder").get("radius"))
    expected_t = [ext["x_m"], ext["y_m"], ext["z_m"] - wheel_radius]
    expected_r = rpy_matrix(*(math.radians(ext[k]) for k in ("roll_deg", "pitch_deg", "yaw_deg")))
    problems = []
    if not close(trans, expected_t):
        problems.append(f"translation {trans} m, camera.json gives {expected_t} m (z_m - wheel_radius {wheel_radius})")
    if not close(sum(rot, []), sum(expected_r, [])):
        problems.append(f"rotation {rot}, camera.json rpy ({ext['roll_deg']}, {ext['pitch_deg']}, {ext['yaw_deg']}) "
                        f"deg gives {expected_r}")
    if not CAMERA_CONVENTION_SETTLED:
        pytest.fail(
            f"{camera_path} exists, but its conventions are not settled (plan conflict, CONTEXT.md 2026-10-10): "
            "is extrinsics z_m above the floor or above the axle, and are roll/pitch/yaw the full base_link -> "
            "camera_optical_frame rotation or small mount angles? Under the reading gen_props.py uses now (floor; "
            "full rotation) the comparison gives: " + ("; ".join(problems) or "a match within 1e-6")
            + ". Once Xiaohui decides, set CAMERA_CONVENTION_SETTLED = True in this file (and adjust the expected "
            "values if the decision differs)."
        )
    assert not problems, "; ".join(problems)


def test_optical_frame_pose_from_measurements(robot, meas, gen_props, car_json_path):
    """base_link -> camera_optical_frame = measured lens position (car.json lens_*_m rows) and REP 103 optical axes
    with the camera rpy ASSUMED 0, for the parts of the pose that gen_props.py did NOT take from camera.json.

    gen_props.extrinsics_used() decides, separately for x/y/z and for roll/pitch/yaw, whether the generated camera_*
    come from configs/camera.json (next to car.json). Those parts are calibrated values, which
    test_optical_frame_matches_camera_json checks, so they are left out here. When camera.json supplies all six, only
    the fixed optical joint is checked and the test skips.
    """
    rpy2 = joint_origin(joint(robot, "camera_optical_joint"))[1]
    assert close(rpy2, [-math.pi / 2, 0.0, -math.pi / 2]), f"optical joint rpy is {rpy2}"
    camera_path = car_json_path.parent / "camera.json"
    xyz_from_camera, rpy_from_camera = gen_props.extrinsics_used(gen_props.read_camera(camera_path))
    rot, trans = optical_pose(robot)
    if not xyz_from_camera:
        floor_to_axle = meas.wheel_diameter() / 2
        expected_t = [meas["lens_x_m"], meas["lens_y_m"], meas["lens_z_m"] - floor_to_axle]
        assert close(trans, expected_t, MEAS_TOL), f"optical frame at {trans}, measured lens at {expected_t}"
    if not rpy_from_camera:
        # REP 103 optical: z forward (+x of the car), x right (-y), y down (-z), while camera rpy is ASSUMED 0.
        assert close(column(rot, 2), [1.0, 0.0, 0.0]), "optical z must point forward"
        assert close(column(rot, 0), [0.0, -1.0, 0.0]), "optical x must point to the robot's right"
        assert close(column(rot, 1), [0.0, 0.0, -1.0]), "optical y must point down"
    if xyz_from_camera and rpy_from_camera:
        pytest.skip(f"{camera_path} supplies x/y/z and roll/pitch/yaw (gen_props.extrinsics_used), so the camera pose "
                    "is the calibration's, not the car.json lens readings': test_optical_frame_matches_camera_json "
                    "checks it (the fixed REP 103 optical joint was checked here)")


def test_caster_touches_floor(robot, meas):
    wheel_radius = meas.wheel_diameter() / 2
    caster_radius = meas["caster_diameter_m"] / 2
    j = joint(robot, "caster_joint")
    assert j.get("type") == "fixed"
    assert j.find("parent").get("link") == "base_link"
    xyz, rpy = joint_origin(j)
    assert close(rpy, [0.0, 0.0, 0.0])
    spheres = link(robot, "caster_link").findall("collision/geometry/sphere")
    assert len(spheres) == 1
    r = float(spheres[0].get("radius"))
    assert r > 0
    assert abs(r - caster_radius) <= MEAS_TOL
    assert abs(xyz[0] - meas["caster_x_m"]) <= MEAS_TOL
    # The sphere's lowest point is on the floor, which is wheel_radius below base_link: exactly the URDF's own wheel
    # radius, and the measured one within MEAS_TOL.
    urdf_wheel_radius = float(link(robot, "left_wheel_link").find("visual/geometry/cylinder").get("radius"))
    assert abs((xyz[2] - r) + urdf_wheel_radius) <= TOL
    assert abs((xyz[2] - r) + wheel_radius) <= MEAS_TOL


