def _props_with_comments(text):
    """Generated car_props.xacro text -> {property name: (the comment line above it, value text)}."""
    lines, out = text.splitlines(), {}
    for i, line in enumerate(lines):
        m = re.match(r'\s*<xacro:property name="([^"]+)" value="([^"]*)"/>', line)
        if m:
            out[m.group(1)] = (lines[i - 1].strip(), m.group(2))
    return out


