# ---------------------------------------------------------------- formatting
def num(v, nd):
    """Fixed decimals with a typographic minus; -0.0 prints as 0.0."""
    s = "%.*f" % (nd, v)
    if float(s) == 0:
        s = s.lstrip("-")
    return s.replace("-", MINUS)


def signed(v, nd):
    s = num(v, nd)
    return s if v < 0 or float("%.*f" % (nd, v)) == 0 else "+" + s


def half_up(v, nd):
    """Round a decimal as printed in its source file half up (36.15 -> 36.2), not as a binary float."""
    q = decimal.Decimal(1).scaleb(-nd)
    return str(decimal.Decimal(repr(v)).quantize(q, rounding=decimal.ROUND_HALF_UP))


def thousands(n):
    return "{:,}".format(int(round(n)))


def pval(p):
    """p-value: about 1 above 0.995, two significant figures down to 0.001, a power of ten below."""
    if p >= 0.995:
        return "\\ensuremath{\\approx}1.00"
    if p >= 0.001:
        return "%.2g" % p
    m, e = ("%.1e" % p).split("e")
    return "\\ensuremath{%s\\times10^{%d}}" % (m, int(e))


def grab(text, pattern, what):
    m = re.search(pattern, text, re.S)
    if not m:
        raise SystemExit("report_assets: cannot find %s (pattern %r)" % (what, pattern))
    return m.groups() if m.lastindex and m.lastindex > 1 else m.group(1)


