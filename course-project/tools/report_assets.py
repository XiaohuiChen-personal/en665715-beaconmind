SUPERSCRIPT = str.maketrans("-0123456789", "\u207b\u2070\u00b9\u00b2\u00b3\u2074\u2075\u2076\u2077\u2078\u2079")


def plain(value):
    """A number's LaTeX text as plain text for a slide: a real minus sign, 7.2 x 10^-5 with superscripts."""
    value = re.sub(r"\\ensuremath\{([\d.]+)\\times10\^\{(-?\d+)\}\}",
                   lambda m: "%s \u00d7 10%s" % (m.group(1), m.group(2).translate(SUPERSCRIPT)), value)
    value = value.replace("\\ensuremath{-}", "\u2212").replace("\\ensuremath{\\approx}", "\u2248")
    value = value.replace("\\,", " ").replace("\\_", "_")
    if "\\" in value or "{" in value:
        raise SystemExit("report_assets: cannot write %r as plain text" % value)
    return value


def slide_outline(numbers_plain, template):
    """Fill {{key}} in the outline template; an unknown key is an error."""
    def fill(m):
        key = m.group(1)
        if key not in numbers_plain:
            raise SystemExit("report_assets: the slide outline uses an unknown key %r" % key)
        return numbers_plain[key]
    note = ("<!-- Generated by course-project/tools/report_assets.py --slides from outline.template.md and the "
            "evidence files; edit the template, not this file. -->\n")
    return note + re.sub(r"\{\{([a-z0-9.-]+)\}\}", fill, template)


