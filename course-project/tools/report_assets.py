def tikz_png(body, out_png, dpi=220):
    """Compile one tikzpicture with pdflatex (preview, tight page) and convert it to PNG with pdftoppm."""
    doc = ("\\documentclass{article}\n\\usepackage{amsmath,amssymb,tikz}\n"
           "\\usetikzlibrary{arrows.meta,positioning}\n"
           "\\usepackage[active,tightpage]{preview}\n\\PreviewEnvironment{tikzpicture}\n"
           "\\setlength\\PreviewBorder{6pt}\n\\begin{document}\n%s\n\\end{document}\n" % body)
    with tempfile.TemporaryDirectory() as tmp:
        tmp = pathlib.Path(tmp)
        (tmp / "fig.tex").write_text(doc)
        run = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error", "fig.tex"], cwd=tmp,
                             capture_output=True, text=True)
        if run.returncode != 0:
            raise SystemExit("report_assets: pdflatex failed for %s:\n%s" % (out_png.name, run.stdout[-1500:]))
        subprocess.run(["pdftoppm", "-png", "-r", str(dpi), "-singlefile", "fig.pdf", "fig"], cwd=tmp, check=True)
        out_png.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(tmp / "fig.png", out_png)


def render_slides(src, figures=True):
    n = build_numbers(src)
    numbers_plain = {k: plain(n[k][0]) for k in sorted(n)}
    files = {"numbers.json": json.dumps(numbers_plain, indent=1, ensure_ascii=False) + "\n"}
    template = SLIDES / "outline.template.md"
    if template.exists():
        files["outline.md"] = slide_outline(numbers_plain, template.read_text())
    if figures:
        room = figure_room(src, scale=2.0)
        body = room[room.index("\\begin{tikzpicture}"):room.index("\\end{tikzpicture}") + len("\\end{tikzpicture}")]
        tikz_png(body.replace("font=\\scriptsize", "font=\\sffamily\\small"), SLIDES / "figures" / "fig-room.png")
        tikz_png(SYSTEM_SKETCH, SLIDES / "figures" / "fig-system.png")
        tikz_png(figure_ate(src), SLIDES / "figures" / "fig-ate.png")
        tikz_png(figure_h1(src), SLIDES / "figures" / "fig-h1.png")
    return files


def pending(tex_path=TEX):
    text = pathlib.Path(tex_path).read_text()
    text = "\n".join(line for line in text.splitlines() if not line.lstrip().startswith("%"))
    return re.findall(r"\\pending\{((?:[^{}]|\{[^{}]*\})*)\}", text)


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--check", action="store_true", help="compare the files on disk with a fresh run")
    ap.add_argument("--pending", action="store_true", help="list the report's \\pending{} placeholders")
    ap.add_argument("--slides", action="store_true", help="write the slides' numbers, outline and figures")
    args = ap.parse_args(argv)
    if args.slides:
        files = render_slides(load())
        SLIDES.mkdir(parents=True, exist_ok=True)
        for name, text in files.items():
            (SLIDES / name).write_text(text)
        print("slides: wrote %s and 4 figures to %s" % (", ".join(sorted(files)), SLIDES.relative_to(ROOT.parent)))
        return 0
    if args.pending:
        items = pending()
        for i, item in enumerate(items, 1):
            print("%2d. %s" % (i, " ".join(item.split())))
        print("pending: %d" % len(items))
        return 0
    src = load()
    files = render(src)
    if args.check:
        stale = [name for name, text in files.items()
                 if not (OUT / name).exists() or (OUT / name).read_text() != text]
        if SLIDES.exists():
            stale += ["slides/" + name for name, text in render_slides(src, figures=False).items()
                      if not (SLIDES / name).exists() or (SLIDES / name).read_text() != text]
        print("assets: up to date" if not stale else "assets: STALE " + ", ".join(stale))
        return 1 if stale else 0
    OUT.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (OUT / name).write_text(text)
    print("assets: wrote %d files to %s (%d numbers)" % (len(files), OUT.relative_to(ROOT.parent),
                                                         len(json.loads(files["numbers.json"]))))
    return 0


if __name__ == "__main__":
    sys.exit(main())
