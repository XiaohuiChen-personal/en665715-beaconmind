    put("gemma.tokens-per-s", grab(h, r"median decoding rate was ([\d.]+) tokens/s", "Gemma decoding rate"),
        "results_summary.md notes at analysis time")
    put("gemma.cap-minutes", grab(h, r"output cap takes about (\d+) minutes", "Gemma cap time"),
        "results_summary.md notes at analysis time")
    fb = grab(h, r"\| 78 \((\d+) no parse, (\d+) output cap\)", "Gemma fallback kinds")
    put("fallbacks.gemma.noparse", fb[0], "results_summary.md run table")
    put("fallbacks.gemma.cap", fb[1], "results_summary.md run table")

    # ---- primary endpoint
    for arm in ["B0", "B1", "B2"] + ARMS:
        a, k = D[arm]["ate_m"], KEY[arm]
        nd = 2 if arm == "B1" else 1
        put("ate.%s.median" % k, num(a["median"] * 100, nd), js + " descriptive ate_m (m to cm)")
