    tags = [per[s]["n_tags"] for s in seeds]
    put("tags.min", min(tags), js + " per_seed n_tags")
    put("tags.max", max(tags), js)
    put("frozen.commit", src["prereg"]["git_commit_short"], "prereg.json git_commit_short")
    put("frozen.files", len(src["prereg"]["files"]), "prereg.json files")
    put("status", S["status"], js + " status")
    if S["status"] != "confirmatory" or S["status_reasons"] or S["missing_steps"]:
        raise SystemExit("report_assets: the analysis is not a clean confirmatory run; rewrite the report text")
    put("sesoi.cm", num(S["sesoi_m"] * 100, 0), js + " sesoi_m")
    put("alpha", "%.2f" % S["alpha"], js)
