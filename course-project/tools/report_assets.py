        put("h1.%s.g1" % k, signed(c["skewness_G1"], 2), js + " confirmatory skewness_G1")
        put("h1.%s.mean" % k, signed(c["mean"] * 100, 2 if abs(c["mean"]) < 0.1 else 1), js + " confirmatory mean")
        ndm = 2 if abs(c["mean"]) < 0.1 else 1
        put("h1.%s.mean-lo" % k, signed(c["mean_boot_ci95"][0] * 100, ndm), js + " confirmatory mean_boot_ci95")
        put("h1.%s.mean-hi" % k, signed(c["mean_boot_ci95"][1] * 100, ndm), js + " confirmatory mean_boot_ci95")
        put("h1.%s.reject" % k, "rejected" if c["reject_h0"] else "not rejected", js + " confirmatory reject_h0")
        put("h1.%s.practical" % k, "yes" if c["practical"] else "no", js + " confirmatory practical")
