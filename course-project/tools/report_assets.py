def walsh_median(d):
    """Hodges-Lehmann point estimate: the median of the Walsh averages (a cross-check of the hand-off only)."""
    w = [(d[i] + d[j]) / 2.0 for i in range(len(d)) for j in range(i, len(d))]
    return statistics.median(w)


