    put("cap.opus", src["prereg"]["design"]["opus_cap_usd"], "prereg.json design")
    put("cap.judge", src["prereg"]["design"]["judge_cap_usd"], "prereg.json design")
    for a in ARMS:
        put("workers." + KEY[a], src["prereg"]["design"]["workers"][a], "prereg.json design workers")
        put("tag." + KEY[a], src["prereg"]["config_tags"][a], "prereg.json config_tags")

