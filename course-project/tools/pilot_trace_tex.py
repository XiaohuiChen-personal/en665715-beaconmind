#!/usr/bin/env python3
"""Turn evidence/M4/M4.T11/trace_example.json (tools/pilot_trace.py) into report/fig_trace.tex.
Thought text is the model's own (truncated with [...]), actions and observations are the logged calls.

Usage: python3 tools/pilot_trace_tex.py evidence/M4/M4.T11/trace_example.json report/fig_trace.tex

AI-assisted: Claude Opus 5.5 via Cursor, 2026-10-29: wrote this generator.
"""
import json
import sys

ESC = {"\\": r"\textbackslash{}", "_": r"\_", "#": r"\#", "%": r"\%", "&": r"\&", "$": r"\$",
       "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}


def esc(s):
    return "".join(ESC.get(c, c) for c in s)


def code(s):
    """Escaped monospace text that may break after commas and colons."""
    return r"{\ttfamily %s}" % esc(s).replace(",", r",\allowbreak{}").replace(":", r":\allowbreak{}")


def cut(s, n):
    s = " ".join(str(s).split())
    return s if len(s) <= n else s[: n - 5].rstrip() + " [...]"


def compact(obj):
    def r(o):
        if isinstance(o, float):
            return round(o, 2)
        if isinstance(o, dict):
            return {k: r(v) for k, v in o.items() if k not in ("pred_range_m", "pred_bearing_deg", "d_range_m", "d_bearing_deg",
                                                               "travel_since_seen_m", "gate_range_m", "gate_bearing_deg")}
        if isinstance(o, list):
            return [r(v) for v in o]
        return o
    return json.dumps(r(obj), separators=(",", ":"))


def main(src, dst):
    t = json.load(open(src))
    obs = t["observation"]
    dets = "; ".join("id %s at %.2f m, %.1f$^\\circ$" % (d["id"], d["range_m"], d["bearing_deg"]) for d in obs["detections"])
    odo = obs["odometry"] or {}
    pp = t["prev_report_pose"] or {}
    rows = [("Input", esc("step %d, last move %s; odometry forward %.2f m, turn " % (
        t["step"], (obs["last_move"] or {}).get("action"), odo.get("forward_m", 0))) + "%.1f$^\\circ$" % odo.get("dtheta_deg", 0)
        + "; previous pose (%.2f, %.2f, %.1f$^\\circ$); detections: " % (pp.get("x_m", 0), pp.get("y_m", 0), pp.get("theta_deg", 0))
        + dets)]
    for turn in t["transcript"]:
        uses = [b for b in turn["blocks"] if b["type"] == "tool_use"]
        results = [b for b in turn["blocks"] if b["type"] == "tool_result"]
        for b in turn["blocks"]:
            if b["type"] == "thinking":
                rows.append(("Thought", esc(cut(b["text"], 230)) if (b["text"] or "").strip()
                             else r"\textit{hidden (the API returned the thinking block without its text)}"))
            elif b["type"] == "text" and b["text"].strip() and not b["text"].strip().startswith("{"):
                rows.append(("Thought", esc(cut(b["text"], 230))))
        for u, r in zip(uses, results):
            rows.append(("Act $\\rightarrow$ Obs", code(cut("%s(%s)" % (u["name"], compact({kk: vv for kk, vv in u["input"].items()
                                                                                              if kk != "pose"})), 110))
                         + r" $\rightarrow$ " + code(cut(compact(r["result"]), 130))))
    rep = t["final_report"] or {}
    assoc = ", ".join("det %s$\\rightarrow$%s (%s)" % (a.get("det"), esc(str(a.get("beacon"))), a.get("result"))
                      for a in rep.get("associations") or [])
    p = rep.get("pose") or {}
    rows.append(("Report", "pose (%.2f, %.2f, %.1f$^\\circ$), " % (p.get("x_m", 0), p.get("y_m", 0), p.get("theta_deg", 0))
                 + esc("pose_source %s; " % rep.get("pose_source")) + assoc + esc("; note: \"%s\"" % rep.get("note"))))
    truth = t["truth"]
    logged = t.get("logged_report") or {}
    key = lambda r: (r.get("pose"), [(a.get("det"), a.get("beacon"), a.get("result")) for a in r.get("associations") or []])
    same = "same" if key(rep) == key(logged) else "a different"
    prior = next((b["result"] for turn in t["transcript"] for b in turn["blocks"]
                  if b["type"] == "tool_result" and b["name"] == "compose_odometry"), {})
    lines = ["% Generated by course-project/tools/pilot_trace_tex.py from evidence/M4/M4.T11/trace_example.json; do not edit.",
             r"\begin{figure*}[t]", r"\centering", r"\scriptsize", r"\renewcommand{\arraystretch}{1.05}",
             r"\begin{tabular}{@{}p{0.085\textwidth}>{\raggedright\arraybackslash}p{0.89\textwidth}@{}}", r"\hline"]
    for role, text in rows:
        lines.append(r"\textbf{%s} & %s \\" % (role, text))
    lines += [r"\hline", r"\end{tabular}",
              r"\caption{Example ReAct trace: one pilot step (seed %d, step %d) re-run with Claude Opus 5.5 and the API's "
              r"summarized-thinking display switched on, so each Thought row is the model's own reasoning summary (the pilot "
              r"runs left it off); the re-run reached the %s pose and associations as the logged step, and its note has %d "
              r"words (the logged note differs only in wording). Each Act$\rightarrow$Obs row is one tool call and its "
              r"result, abridged (gate widths, predicted ranges and residuals omitted) and rounded to "
              r"two decimals; the pose argument is omitted (the previous pose for \texttt{compose\_odometry}, the prior "
              r"$(%.2f, %.2f, %.1f^\circ)$ for the other calls). The third detection is a second "
              r"tag with ID 21, 2.75\,m from B21, so it becomes B21b. True pose: (%.2f, %.2f, %.1f$^\circ$).}" % (
                  t["seed"], t["step"], same, len((rep.get("note") or "").split()), prior.get("x_m", 0), prior.get("y_m", 0),
                  prior.get("theta_deg", 0), truth["x_m"], truth["y_m"], truth["theta_deg"]),
              r"\label{fig:trace}", r"\end{figure*}"]
    open(dst, "w").write("\n".join(lines) + "\n")
    print("wrote %s: %d rows" % (dst, len(rows)))


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
